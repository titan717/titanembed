// Writes a license report for every installed package and fails on licenses outside the allowlist.
import { readFileSync, writeFileSync } from "node:fs";

const lock = JSON.parse(readFileSync("package-lock.json", "utf8"));
const allowed = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|CC0-1\.0|CC-BY-4\.0|BlueOak-1\.0\.0|Python-2\.0|OFL-1\.1|MPL-2\.0|Unlicense|\(MIT OR CC0-1\.0\)|MIT OR Apache-2\.0|Apache-2\.0 OR MIT|\(MIT AND CC-BY-3\.0\)|\(BSD-2-Clause OR MIT OR Apache-2\.0\))$/;
const rows = [];
const bad = [];
for (const [path, info] of Object.entries(lock.packages ?? {})) {
  if (!path) continue;
  const name = path.replace(/^.*node_modules\//, "");
  let license = info.license;
  if (!license) {
    try {
      const pj = JSON.parse(readFileSync(path + "/package.json", "utf8"));
      license = pj.license ?? (pj.licenses && pj.licenses.map((l) => l.type).join(" OR "));
    } catch {
      /* optional package not installed on this platform */
    }
  }
  license = license || "UNKNOWN";
  const scope = info.dev ? "dev" : "runtime";
  rows.push({ name, version: info.version, license, scope });
  if (!allowed.test(license) && !(info.optional && license === "UNKNOWN")) bad.push(`${name}@${info.version} (${license})`);
}
rows.sort((a, b) => a.name.localeCompare(b.name));
const runtime = rows.filter((r) => r.scope === "runtime");
const md = [
  "# Third-party licenses",
  "",
  "Generated by `npm run licenses` from package-lock.json.",
  "",
  "## Shipped in the player (runtime)",
  "",
  "| Package | Version | License |",
  "| --- | --- | --- |",
  ...runtime.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  "",
  `## Build and test tools (${rows.length - runtime.length} packages, not shipped)`,
  "",
  "| Package | Version | License |",
  "| --- | --- | --- |",
  ...rows.filter((r) => r.scope === "dev").map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  ""
].join("\n");
writeFileSync("docs/LICENSES.md", md);
console.log(`${rows.length} packages, ${runtime.length} shipped. Report: docs/LICENSES.md`);
if (bad.length) {
  console.error("Licenses outside the allowlist:\n  " + bad.join("\n  "));
  process.exit(1);
}
